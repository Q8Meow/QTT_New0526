"""Central PR165-B memory status vocabulary."""

from __future__ import annotations


MEMORY_CLASSIFICATIONS = (
    "POSITIVE_CONDITION_SCOPED_PREFERRED",
    "POSITIVE_CONDITION_SCOPED_WATCH",
    "NEUTRAL_INSUFFICIENT_EVIDENCE",
    "FRAGILE_HIGH_VARIANCE",
    "NEGATIVE_CONDITION_SCOPED_AVOID",
    "NEGATIVE_CONDITION_SCOPED_COOLDOWN",
    "NEGATIVE_RETEST_REQUIRED",
    "NEGATIVE_REPAIR_REQUIRED",
    "COST_DOMINATED",
    "LATENCY_DOMINATED",
    "LIQUIDITY_DOMINATED",
    "ADVERSE_SELECTION_DOMINATED",
    "MODEL_RISK_DOMINATED",
    "SOURCE_PROVENANCE_WEAK",
    "REPAIR_CONFIDENCE_WEAK",
    "YES_NO_COMPLEMENT_INCONSISTENT",
    "CAPITAL_LOCK_DOMINATED",
    "PORTFOLIO_CROWDING_DOMINATED",
    "DUPLICATE_EDGE_DOMINATED",
    "FALSE_DISCOVERY_RISK_WATCH",
    "SPARSE_REGIME_WATCH",
    "QUANTUM_FORMULATION_WEAK",
    "QUANTUM_CLASSICAL_COMPARATOR_WEAK",
    "STRUCTURAL_INVALIDITY_ARCHIVE_CANDIDATE",
)

OUTCOME_SIGNS = ("POSITIVE", "NEGATIVE", "NEUTRAL", "MIXED", "INSUFFICIENT_EVIDENCE")
MEMORY_CONFIDENCE_TIERS = ("HIGH", "MEDIUM", "LOW", "WATCH")
MEMORY_MATERIALITY_TIERS = ("HIGH", "MEDIUM", "LOW")
FRAGILE_CLASSIFICATIONS = (
    "FRAGILE_HIGH_VARIANCE",
    "FALSE_DISCOVERY_RISK_WATCH",
    "SPARSE_REGIME_WATCH",
)
POSITIVE_CLASSIFICATIONS = (
    "POSITIVE_CONDITION_SCOPED_PREFERRED",
    "POSITIVE_CONDITION_SCOPED_WATCH",
)


def is_positive(classification: str) -> bool:
    return classification in POSITIVE_CLASSIFICATIONS


def is_fragile(classification: str) -> bool:
    return classification in FRAGILE_CLASSIFICATIONS


def is_non_positive_memory(classification: str) -> bool:
    return classification not in POSITIVE_CLASSIFICATIONS
