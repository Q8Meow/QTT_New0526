"""SourceAcquisitionCandidateV1 records for PR162R-B."""

from __future__ import annotations

from typing import Any

from .binding_family_classifier import target_field, unit_for_family
from .dataset_contracts import source_locator_for


def build_source_candidates(tasks: list[dict[str, Any]]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    seen: set[tuple[str, str, str]] = set()
    for task in tasks:
        for source_class in _source_classes(task):
            key = (task["binding_family"], task["venue_scope"], source_class)
            if key in seen:
                continue
            seen.add(key)
            rows.append(
                {
                    "source_candidate_id": f"PR162R_B_SOURCE_CANDIDATE::{len(rows) + 1:04d}",
                    "source_class": source_class,
                    "source_locator": source_locator_for(task["venue_scope"], task["binding_family"]),
                    "observed_at_utc": "2026-06-05T00:00:00Z",
                    "binding_family": task["binding_family"],
                    "target_field": target_field(task["binding_family"]),
                    "unit": unit_for_family(task["binding_family"]),
                    "scale": task["scale"],
                    "venue_scope": task["venue_scope"],
                    "market_scope": "BINARY_EVENT_MARKET",
                    "data_granularity": task["data_granularity"],
                    "extraction_basis": _extraction_basis(source_class),
                    "candidate_truth_status": source_class,
                    "replay_allowed": task["replay_or_paper_lane"] in {"REPLAY", "BOTH"},
                    "paper_allowed": task["replay_or_paper_lane"] in {"PAPER", "BOTH"},
                    "live_allowed": False,
                    "promotion_requires_later_source_acceptance": True,
                    "promotion_requires_replay_paper_evidence": True,
                    "owner_override_allowed_for_internal_priority": True,
                    "owner_override_cannot_fabricate_external_fact": True,
                    "unsafe_duplicate_irrelevant_unmappable_reason": "",
                    "live_order_authority": False,
                    "validation_status": "PASS",
                }
            )
    return rows


def source_candidate_for_task(
    task: dict[str, Any],
    source_candidates: list[dict[str, Any]],
) -> dict[str, Any]:
    preferred = "SYNTHETIC_TEST_FIXTURE" if (
        task["venue_scope"] == "VENUE_NEUTRAL_SYNTHETIC_FIXTURE" or task["binding_family"].startswith(("PAPER_", "QUANTUM_"))
    ) else "REPO_LOCAL_ARTIFACT_CANDIDATE"
    for row in source_candidates:
        if (
            row["binding_family"] == task["binding_family"]
            and row["venue_scope"] == task["venue_scope"]
            and row["source_class"] == preferred
        ):
            return row
    for row in source_candidates:
        if row["binding_family"] == task["binding_family"] and row["venue_scope"] == task["venue_scope"]:
            return row
    raise KeyError(task["binding_task_id"])


def _source_classes(task: dict[str, Any]) -> tuple[str, ...]:
    classes = ["REPO_LOCAL_ARTIFACT_CANDIDATE", "SYNTHETIC_TEST_FIXTURE"]
    if task["venue_scope"] != "VENUE_NEUTRAL_SYNTHETIC_FIXTURE":
        classes.insert(0, "OFFICIAL_SOURCE_CANDIDATE")
        classes.append("NON_OFFICIAL_WEB_CANDIDATE")
    if task["binding_family"] in {
        "HISTORICAL_ORDERBOOK_SNAPSHOT_SERIES",
        "HISTORICAL_TRADE_SERIES",
        "CROSS_VENUE_DISAGREEMENT_INPUTS",
        "STALENESS_AND_FRESHNESS_INPUTS",
    }:
        classes.append("RESEARCH_SOURCE_CANDIDATE")
        classes.append("PUBLIC_DATASET_CANDIDATE")
    return tuple(classes)


def _extraction_basis(source_class: str) -> str:
    if source_class == "SYNTHETIC_TEST_FIXTURE":
        return "deterministic repo-local non-live fixture generated by PR162R-B"
    if source_class == "REPO_LOCAL_ARTIFACT_CANDIDATE":
        return "repo-local artifact candidate normalized through PR162R-B fixture binding"
    return "authoring-time source locator only; no runtime retrieval or source acceptance"
