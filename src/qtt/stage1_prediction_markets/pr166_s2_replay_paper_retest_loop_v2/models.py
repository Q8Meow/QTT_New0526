    downstream_artifact_refs = list(downstream_artifact_refs or [c.MANIFEST_REF])
    future_connector_pr_refs = list(future_connector_pr_refs or ["DASHBOARD_GOVERNANCE_COMMANDER_REVIEW"])
    return {
        "artifact_id": artifact_id,
        "row_id": row_id,
        "created_by_pr": c.PR_ID,
        "roadmap_pr_id": c.PR_ID,
        "candidate_packet_id": candidate_packet_id,
        "qku_id": qku_id,
        "formula_id": formula_id,
        "algorithm_id": algorithm_id,
        "parameter_stack_id": parameter_stack_id,
        "condition_fingerprint_id": condition_fingerprint_id,
        "scenario_group_id": scenario_group_id,
        "episode_id": episode_id,
        "order_intent_id": order_intent_id,
        "fill_id": fill_id,
        "no_fill_id": no_fill_id,
        "upstream_pr_refs": list(c.UPSTREAM_PR_REFS),
        "upstream_artifact_refs": list(upstream_artifact_refs or [c.MANIFEST_REF]),
        "upstream_row_refs": list(upstream_row_refs or [row_id]),
        "upstream_value_refs": list(upstream_value_refs or ["candidate_packet_id"]),
        "source_roadmap_pr_refs": list(c.UPSTREAM_PR_REFS),
        "source_artifact_refs": list(source_artifact_refs or upstream_artifact_refs or [c.MANIFEST_REF]),
        "source_row_refs": list(source_row_refs or upstream_row_refs or [row_id]),
        "input_shard_refs": list(input_shard_refs or ["ROOT_REPORT_RECORD"]),
        "replay_paper_execution_status": replay_paper_execution_status,
        "simulated_order_authority": "NONLIVE_REPLAY_PAPER_ONLY",
        "result_status": result_status,
        "replay_paper_net_edge_after_costs": replay_paper_net_edge_after_costs,
        "edge_lower_confidence_bound": edge_lower_confidence_bound,
        "result_confidence_score": result_confidence_score,
        "tca_result_ref": tca_result_ref,
        "implementation_shortfall_ref": implementation_shortfall_ref,
        "fill_realism_score": fill_realism_score,
        "calibration_score": calibration_score,
        "no_leakage_audit_ref": no_leakage_audit_ref,
        "overfit_fdr_ref": overfit_fdr_ref,
        "capacity_crowding_ref": capacity_crowding_ref,
        "quantum_handoff_ref": quantum_handoff_ref,
        "agent_duty_ref": agent_duty_ref,
        "downstream_pr_refs": downstream_pr_refs,
        "downstream_artifact_refs": downstream_artifact_refs,
        "downstream_agent_consumers": list(
            downstream_agent_consumers
            or [
                "parameter_selector_agent",
                "risk_manager_agent",
                "quantum_optimizer_agent",
                "dashboard_agent",
                "governance_agent",
                "commander_agent",
            ]
        ),
        "owning_agent": owning_agent,
        "reviewer_or_challenger_agent": reviewer_or_challenger_agent,
        "validator_ref": c.VALIDATOR_REF,
        "manifest_ref": c.MANIFEST_REF,
        "schema_ref": c.REPORT_SCHEMA_REFS[report_filename],
        "authority_boundary_ref": c.AUTHORITY_BOUNDARY_REF,
        "authority_boundary": "REPLAY_PAPER_ONLY_NO_LIVE_OR_SOURCE_TRUTH_AUTHORITY",
        "no_orphan_status": no_orphan_status,
        "terminal_status_flag": terminal_status_flag,
        "terminal_status_reason": terminal_status_reason,
        "deterministic_sort_key": row_id,
        "connector_dependency_class": connector_dependency_class,
        "venue_semantic_dependency_class": venue_semantic_dependency_class,
        "future_connector_pr_refs": future_connector_pr_refs,
        "future_venue_readiness_route": future_venue_readiness_route,
        "connector_binding_allowed_in_this_pr": False,
        "private_state_fetch_allowed_in_this_pr": False,
        "runtime_cash_receipt_allowed_in_this_pr": False,
        "source_truth_acceptance_allowed_in_this_pr": False,
        "live_order_authority_allowed": False,
        "created_at_utc": c.CREATED_AT_UTC,
        "validation_status": c.VALIDATION_STATUS,
        "raw_values": raw_values or {},
        "normalized_values": normalized_values or {},
        "unit_class_by_field": unit_class_by_field
        or {
            "replay_paper_net_edge_after_costs": UnitClass.SIGNED_NORMALIZED_MINUS1_1.value,
            "edge_lower_confidence_bound": UnitClass.SIGNED_NORMALIZED_MINUS1_1.value,
            "result_confidence_score": UnitClass.NORMALIZED_0_1.value,
        },
        "sign_convention_by_field": sign_convention_by_field
        or {
            "replay_paper_net_edge_after_costs": "SIGNED_POSITIVE_IS_BETTER_REPLAY_PAPER_ONLY",
            "edge_lower_confidence_bound": "SIGNED_POSITIVE_IS_BETTER_REPLAY_PAPER_ONLY",
            "cost_drag_ratio": "NON_NEGATIVE_LOWER_IS_BETTER",
        },
        **authority_zero_counts(),
    }
