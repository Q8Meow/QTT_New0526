    future_venue_readiness_route: str = "DASHBOARD_GOVERNANCE_COMMANDER_REVIEW",
    raw_values: dict[str, Any] | None = None,
    normalized_values: dict[str, Any] | None = None,
    unit_class_by_field: dict[str, str] | None = None,
    sign_convention_by_field: dict[str, str] | None = None,
