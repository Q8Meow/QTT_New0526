def _dataset_record(
    *,
    repo_root: Path,
    dataset_id: str,
    family: str,
    lifecycle_state: str,
    authority_class: str,
    source_class: str,
    source_name: str,
    source_platform_or_venue: str,
    source_endpoint_family: str,
    source_locator: str,
    access_rights_status: str,
    materialization_mode: str,
    materialization_plan_ref: str,
    repo_local_path: Path | None,
    file_type: str,
    row_count: int,
    time_window_start: str | None,
    time_window_end: str | None,
    qku_scope_refs: list[str],
    run_capable: bool,
    blocker_code: str,
    blocked_reason: str | None,
    synthetic_fixture: bool = False,
    credential_required: bool = False,
) -> dict[str, Any]:
    rel = repo_relative_posix(repo_root, repo_local_path) if repo_local_path is not None else None
    size = repo_local_path.stat().st_size if repo_local_path is not None and repo_local_path.exists() else 0
    return {
        "record_id": dataset_id,
        "dataset_id": dataset_id,
        "created_by_pr": c.PR_ID,
        "authority_class": c.AUTHORITY_CLASS,
        "dataset_family": family,
        "dataset_lifecycle_state": lifecycle_state,
        "dataset_authority_class": authority_class,
        "source_class": source_class,
        "source_locator": source_locator,
        "source_name": source_name,
        "source_platform_or_venue": source_platform_or_venue,
        "source_endpoint_family": source_endpoint_family,
        "source_revalidation_required_flag": True,
        "access_rights_status": access_rights_status,
        "access_rights_notes": "candidate_only_non_authoritative_use",
        "owner_attestation_required_flag": access_rights_status != "PUBLIC_UNAUTHENTICATED_CANDIDATE_USE_OK",
        "owner_attestation_status": "NOT_REQUIRED" if access_rights_status == "PUBLIC_UNAUTHENTICATED_CANDIDATE_USE_OK" else "REQUIRED_NOT_PRESENT",
        "materialization_mode": materialization_mode,
        "materialization_plan_ref": materialization_plan_ref,
        "repo_local_path": rel,
        "relative_posix_path": rel,
        "file_type": file_type,
        "size_bytes": size,
        "size_class": file_size_class(size),
        "compression_type": None,
        "row_count_candidate": row_count,
        "time_window_start": time_window_start,
        "time_window_end": time_window_end,
        "time_granularity": "event_time_and_one_minute_candle" if row_count else None,
        "market_scope": "PREDICTION_MARKET",
        "venue_scope": source_platform_or_venue,
        "event_category_scope": "SPORTS_MULTIGAME_EVENT_CONTRACT_CANDIDATE",
        "qku_scope_refs": qku_scope_refs,
        "scenario_refs": ["PR162A_SCENARIO_SCOPE_PR161F_REPLAY_PAPER"] if run_capable else [],
        "market_bundle_refs": ["PR162A_MARKET_BUNDLE_SCOPE_GENERIC_BINARY_PRICE_SERIES"] if run_capable else [],
        "pr161f_run_plan_refs": ["PR162A_PR161F_RUN_PLAN_SCOPE_MAPPED"] if run_capable else [],
        "pr162_adapter_refs": [
            "PR162_ReplayDataAdapterContract.report.json",
            "PR162_PaperDataAdapterContract.report.json",
        ] if run_capable else [],
        "replay_lane_eligible_flag": run_capable,
        "paper_lane_eligible_flag": run_capable,
        "quantum_qku_eligible_flag": run_capable,
        "quantum_encoding_feature_eligible_flag": run_capable,
        "classical_baseline_feature_eligible_flag": run_capable,
        "hybrid_comparator_feature_eligible_flag": run_capable,
        "run_capable_flag": run_capable,
        "run_capable_gate_status": "RUN_CAPABLE_GATE_PASSED" if run_capable else "RUN_CAPABLE_GATE_BLOCKED",
        "dataset_coverage_state": c.VENUE_SCOPED_RUN_CAPABLE_READY
        if run_capable
        else c.RUN_CAPABLE_BLOCKED_PR162B_REQUIRES_STRICT_DATASET_COVERAGE,
        "candidate_only_flag": True,
        "adapter_mechanics_fixture_flag": False,
        "dataset_seed_candidate_flag": False,
        "quantum_feature_seed_candidate_flag": False,
        "synthetic_fixture_flag": synthetic_fixture,
        "smoke_fixture_flag": synthetic_fixture,
        "private_state_flag": False,
        "live_connector_dependency_flag": False,
        "order_endpoint_dependency_flag": False,
        "credential_required_flag": credential_required,
        "data_quality_status": "PASS" if run_capable else "WARNING_CANDIDATE_ONLY",
        "schema_validation_status": "PASS" if run_capable else "WARNING_CANDIDATE_ONLY",
        "normalization_status": "NORMALIZED" if run_capable else "NOT_NORMALIZED",
        "leakage_audit_status": "PASS" if run_capable else "WARNING_CANDIDATE_ONLY",
        "duplicate_status": "UNIQUE" if run_capable else "NOT_APPLICABLE",
        "blocked_reason": blocked_reason,
        "blocker_code": blocker_code,
        "downstream_agent_routes": list(c.AGENT_ROLES),
        "downstream_pr_routes": list(c.DOWNSTREAM_PR_ROUTES),
    }
