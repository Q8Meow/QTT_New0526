def _owning_agent_for_family(family: str) -> str:
    if family in {"QUBO_OBJECTIVE", "BQM_OBJECTIVE", "ISING_OBJECTIVE", "CQM_OBJECTIVE", "DQM_OBJECTIVE", "QUADPROGRAM_OBJECTIVE", "CLASSICAL_FALLBACK_OBJECTIVE"}:
        return "Quantum AutoMapper Agent"
    if family in {"TCA_DECOMPOSITION", "IMPLEMENTATION_SHORTFALL", "SPREAD_COST", "EXPLICIT_FEE_COST", "SLIPPAGE_COST", "MARKET_IMPACT", "ADVERSE_SELECTION"}:
        return "Execution/TCA Agent"
    if family in {"QUEUE_FILL_PROBABILITY", "PARTIAL_FILL", "LATENCY_DECAY"}:
        return "Fill/Queue/Latency Agent"
    if family in {"PORTFOLIO_MARGINAL_UTILITY", "RISK_BUDGET", "EXPECTED_SHORTFALL_CVAR", "ROBUST_COVARIANCE_OR_HRP_CLUSTER", "CAPACITY_CROWDING"}:
        return "Portfolio/Risk Agent"
    if family in {"OVERFIT_FDR", "LOWER_CONFIDENCE_BOUND", "CONFORMAL_LCB_OR_UNCERTAINTY_RANKING", "BAYESIAN_SHRINKAGE_CALIBRATION"}:
        return "Algorithm Materialization Agent"
    if family in {"CHAMPION_CHALLENGER_ARBITRATION", "REGIME_CONDITIONED_MEMORY"}:
        return "Regime Memory Agent"
    return "Formula Materialization Agent"


