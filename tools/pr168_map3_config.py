def materialized_rows() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for source in ONLINE_SCOUT_ROWS:
        if source["rejected_flag"]:
            continue
        formula_id = f"FORM_MAP3_{source['scout_row_id'].replace('SCOUT_', '')}"
        row = {
            "formula_materialization_row_id": f"MAT_{source['scout_row_id']}",
            "formula_id": formula_id,
            "formula_variant_id": f"FVAR_{formula_id}_BASE",
            "external_candidate_id": f"EXT_{source['scout_row_id']}",
            "source_url": source["source_url"],
            "formula_family": source["formula_family_candidate"],
            "safe_formula_expression_or_semantic_definition": source[
                "candidate_expression_or_semantic_definition"
            ],
            "required_inputs_with_units": [
                {"input_id": item, "unit": source["unit_requirements"][0] if source["unit_requirements"] else "unspecified"}
                for item in source["required_inputs_candidate"]
            ],
            "materialization_path": source["materialization_path"],
            "computability_route": (
                "COMPUTABLE_NOW_REPLAY_PAPER_CANDIDATE"
                if source["materialization_path"] == MATERIALIZED
                else "COMPUTABLE_AFTER_FORMULA_INPUT_REPAIR"
                if source["materialization_path"] == SEMANTIC_REPAIR
                else "COMPUTABLE_AFTER_SOURCE_EVIDENCE_REVIEW"
            ),
            "formula_output_type": "candidate_numeric_or_semantic_contract",
            "candidate_only_flag": True,
            "accepted_truth_flag": False,
            "not_profit_proof_flag": True,
            "champion_allowed_flag": False,
            "live_candidate_allowed_flag": False,
            **common_route("FORMULA_MATERIALIZATION_CANDIDATE_NON_PROOF"),
        }
        row["source_refs"] = [source["source_url"]]
        row["data_requirement_refs"] = [f"DATAREQ_{formula_id}"]
        row["unit_normalization_refs"] = [f"UNIT_{formula_id}"]
        row["formula_contract_refs"] = (
            [f"FormulaPluginContractV1:{formula_id}"]
            if source["materialization_path"] == MATERIALIZED
            else []
        )
        rows.append(row)
    return rows
