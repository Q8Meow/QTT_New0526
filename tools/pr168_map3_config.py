def _source(
    row_id: str,
    family: str,
    query: str,
    url: str,
    title: str,
    tier: str,
    formula_family: str,
    expression: str,
    inputs: list[str],
    materialization_path: str,
    data_family: str,
    units: list[str],
    route: str = "PR168_RP2_REPLAY_PAPER_RECOMPUTE",
    rejected: bool = False,
    reject_reason: str | None = None,
) -> dict[str, Any]:
    row = {
        "scout_row_id": row_id,
        "query_family": family,
        "query_text_or_source_url": query,
        "source_url": url,
        "source_title": title,
        "source_tier": tier,
        "retrieved_at_utc": CREATED_AT_UTC,
        "useful_formula_or_input_found_flag": not rejected,
        "formula_family_candidate": formula_family,
        "candidate_expression_or_semantic_definition": expression,
        "required_inputs_candidate": inputs,
        "data_family_requirements": [data_family],
        "unit_requirements": units,
        "candidate_only_flag": True,
        "accepted_truth_flag": False,
        "rejected_flag": rejected,
        "reject_reason_if_any": reject_reason,
        "source_evidence_review_route": "SOURCE_EVIDENCE_REVIEW",
        "RP2_or_RANK2_route_if_computable": route,
        "materialization_path": materialization_path,
        "formula_intake_state": materialization_path,
        "authority_class": "EXTERNAL_CANDIDATE_NON_PROOF",
        "not_profit_proof_flag": True,
        "champion_allowed_flag": False,
        "live_candidate_allowed_flag": False,
        **common_route("EXTERNAL_CANDIDATE_NON_PROOF"),
    }
    row["source_refs"] = [url]
    return row


